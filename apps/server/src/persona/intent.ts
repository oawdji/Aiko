/**
 * 风格调整意图检测（纯规则，无 LLM）。
 * 用途：
 *  1. 记忆抽取 gate——风格调整消息不进事实抽取（避免双轨生效）；
 *  2. 二期聊天内流提示（data-persona-suggestion）复用。
 * 保守词表：宁可漏判（用户可在面板显式发起），不可误判（闲聊被误拦）。
 */

const STYLE_PATTERNS: RegExp[] = [
  /更(简洁|简短|详细|细致|热情|温暖|高冷|冷淡|幽默|严肃|活泼|正式|随意)/,
  /(简洁|简短|详细|热情|幽默|严肃|活泼)一点/,
  /(回答|回复|说话|语气|风格)(不要|别)?(太|再|稍微)?(啰嗦|话多|冗长|简短|长了|正式|随意)/,
  /(少|别总是?|不要总是)(问|反问)/,
  /多问(问)?我/,
  /(调整|修改|更改)(一下|下)?(你的)?(语气|风格|说话方式|表达方式)/,
  /以后(回答|回复|说话)(尽量)?(简短|简洁|详细)/,
];

export function looksLikeStyleAdjustment(text: string): boolean {
  return STYLE_PATTERNS.some((re) => re.test(text));
}
